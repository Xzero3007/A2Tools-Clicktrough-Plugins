"""Builds the Closet plugin's data.js: every skin item with its name, grade,
slot, icon and the closet entry it fills.

  python3 -I dev/make_data.py

Reads ../inventory/data.js (the Inventory plugin's item list: SkeeveAN's
Aion-DPS-Meter, MIT, and Aion2Data). A skin's closet entry comes from its icon,
which names the look's number:
  WP_<weapon>_<NNNN>_...   -> 1 NNNN <piece 101-108>  (weapons)
  GM_<NNNN>_Tnn_<part>     -> 3 NNNN <piece 101-107>  (armour)
  ACC_<NL|ER>_<NNNN>       -> 5 NNNN <103 | 101>      (necklace, earrings)
Skins whose icon has no number (sets, costumes) get no entry: the plugin
learns theirs when one is bought.
"""
import json, os, re

WEAPONS = {"GS": (101, "Greatsword"), "SW": (102, "Longsword"), "DA": (103, "Dagger"), "BW": (104, "Bow"),
           "MB": (105, "Spellbook"), "OR": (106, "Orb"), "MA": (107, "Mace"), "ST": (108, "Staff")}
ARMOUR = {"Torso": 101, "Pants": 102, "Helmet": 103, "Shoulder": 104, "Gloves": 105, "Boots": 106, "Cape": 107}
JEWEL = {"NL": 103, "ER": 101}


def closet_id(icon):
    m = re.match(r"WP_([A-Z]{2})_(\d{4})", icon)
    if m and m.group(1) in WEAPONS:
        return 10000000 + int(m.group(2)) * 1000 + WEAPONS[m.group(1)][0]
    m = re.match(r"GM_(\d{4})_T\d\d_([A-Za-z]+)$", icon)
    if m and m.group(2) in ARMOUR:
        return 30000000 + int(m.group(1)) * 1000 + ARMOUR[m.group(2)]
    m = re.match(r"ACC_(NL|ER)_(\d{4})$", icon)
    if m:
        return 50000000 + int(m.group(2)) * 1000 + JEWEL[m.group(1)]
    return 0


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src = open(os.path.join(here, "..", "inventory", "data.js"), encoding="utf-8").read()
    items = json.loads(src[src.index("{"):src.rindex("}") + 1])["items"]
    skins = {}
    for k, (name, grade, icon) in sorted(items.items(), key=lambda kv: int(kv[0])):
        m = re.match(r"(.*) \(Skin: ([^)]+)\)", name)
        if not m:
            continue
        skins[k] = [m.group(1), grade, m.group(2), icon or "", closet_id(icon or "")]
    out = {
        "source": "Item names, grades and icons: the Inventory plugin's list (SkeeveAN's Aion-DPS-Meter, MIT, and Aion2Data)",
        "skins": skins,
    }
    with open(os.path.join(here, "data.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by dev/make_data.py from the Inventory plugin's data.js (SkeeveAN's Aion-DPS-Meter,\n")
        f.write("// MIT, and Aion2Data). AION 2 names and game data belong to NCSOFT. Do not edit by hand.\n")
        f.write("globalThis.CLOSET_DATA = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    mapped = sum(1 for v in skins.values() if v[4])
    print(f"{len(skins)} skins, {mapped} with a closet entry")


main()
