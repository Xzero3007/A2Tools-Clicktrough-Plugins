"""Builds the Inventory plugin's data.js: every item's name, grade and icon,
and the game's content tickets (the keys and entry counts).

  python3 -I dev/make_data.py <SkeeveAN checkout> <cache folder>

From SkeeveAN's Aion-DPS-Meter (MIT, https://github.com/SkeeveAN/Aion-DPS-Meter),
read from the game's client:
  Client/assets/aion2/items/item_names.json   item id -> grade, names
  Client/assets/aion2/items/item_icons.json   gear's icons (the game's names)
  Client/assets/aion2/craft/item_icons.json   crafting items' icons
  Client/assets/aion2/tickets/tickets.json    the content tickets
From Aion2Data (aion2data.com, an unofficial fan reference that reads AION 2's
game files): every other item's icon, and the names of items SkeeveAN's list
lacks (<cache>/icons.json and its pages, made by dev/fetch_icons.py).
The icons are the game's icon server's names; the plugin asks the meter for
the pictures (assets.playnccdn.com).
"""
import json, os, re, subprocess, sys
from html import unescape

GRADES = {"Common": 1, "Rare": 2, "Legend": 3, "Unique": 4, "Epic": 5, "Mythic": 6, "Special": 7}


def main():
    sk, cache = sys.argv[1], sys.argv[2]
    out = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    a = os.path.join(sk, "Client/assets/aion2")
    names = json.load(open(os.path.join(a, "items/item_names.json")))
    gear = json.load(open(os.path.join(a, "items/item_icons.json")))
    craft = json.load(open(os.path.join(a, "craft/item_icons.json")))
    tickets = json.load(open(os.path.join(a, "tickets/tickets.json")))["tickets"]
    a2d = json.load(open(os.path.join(cache, "icons.json")))
    # Aion2Data's names and grades of the items SkeeveAN's list lacks.
    extra = {}
    for f in sorted(os.listdir(cache)):
        if not f.startswith("c-"):
            continue
        page = open(os.path.join(cache, f)).read()
        for item, inner in re.findall(r'<a[^>]*href="/items/(\d+)-[^"]*"[^>]*>(.*?)</a>', page, re.S):
            if item in names or item in extra:
                continue
            alt = re.search(r'alt="([^"]+)"', inner)
            grade = re.search(r'data-grade="([A-Za-z]+)"', inner)
            if alt:
                extra[item] = [GRADES.get(grade.group(1), 0) if grade else 0, unescape(alt.group(1))]
    items = {}
    for i, row in list(names.items()) + list(extra.items()):
        # The game's own names for gear first (Aion2Data shortens some).
        icon = gear.get(i) or craft.get(i) or a2d.get(i)
        items[i] = [row[1], row[0], icon[5:] if icon and icon.startswith("Icon_") else icon]
    t = {}
    for x in tickets:
        reset = "d" if "daily" in x else "w" if "weekly" in x else None
        t[str(x["id"])] = [x["names"]["en"], x.get("short", {}).get("en") or x["names"]["en"], x.get("max", 0),
                           x.get("subscribeMax", 0), bool(x.get("perServer")), bool(x.get("time")), reset]
    rev = subprocess.run(["git", "-C", sk, "log", "-1", "--format=%h"], capture_output=True, text=True).stdout.strip()
    data = {
        "source": {"items": f"SkeeveAN's Aion-DPS-Meter (MIT) {rev}; icons also Aion2Data", "tickets": "SkeeveAN's Aion-DPS-Meter"},
        "items": dict(sorted(items.items(), key=lambda kv: int(kv[0]))),
        "tickets": t,
    }
    with open(os.path.join(out, "data.js"), "w", encoding="utf8") as f:
        f.write("// Generated by dev/make_data.py from SkeeveAN's Aion-DPS-Meter (MIT): item names, grades, the gear's and\n")
        f.write("// crafting items' icons and the content tickets, read from the game's client; the other items' icons\n")
        f.write("// from Aion2Data (aion2data.com). Icons without their \"Icon_\". Do not edit by hand.\n")
        f.write("// AION 2 names and game data belong to NCSOFT.\n")
        f.write("globalThis.INVENTORY_DATA = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"{len(items)} items ({sum(1 for v in items.values() if v[2])} with an icon, {len(extra)} from Aion2Data), {len(t)} tickets")


if __name__ == "__main__":
    main()
