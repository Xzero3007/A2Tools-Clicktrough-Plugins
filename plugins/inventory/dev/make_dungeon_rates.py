"""Writes dungeon-rates.js: the game's dungeon drop rates (AION 2 Global, the
game's own reward tables), per dungeon and mode, the chance a reward box
(one clear: every boss's pools) drops each item at least once, and which of
the game's zones is which mode.

  python3 -I dev/make_dungeon_rates.py <rates.json> > dungeon-rates.js

rates.json: { gameVersion, dungeons: { name: { mode: [{ itemId, name, grade,
category, chancePerClear }] } } }, read from the game's files. Only the
items that drop now and then (not every clear) of grade Rare and up are
kept. The zones come from zones.js (the game's dungeon ids): a dungeon's id
ending in 1 is taken as its Normal (Exploration) mode, the others as Hard
(Conquest); a dungeon with one zone only takes its one mode.
"""
import json, os, re, sys

here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = json.load(open(sys.argv[1]))
zones_js = open(os.path.join(here, "zones.js")).read()
zones = json.loads(re.search(r"INVENTORY_ZONES = (\{.*\});", zones_js).group(1))

GRADES = ("Rare", "Legend", "Unique", "Epic", "Mythic")
out = {"gameVersion": src.get("gameVersion"), "dungeons": {}, "zones": {}}
for name, modes in src["dungeons"].items():
    kept = {}
    for mode, items in modes.items():
        if not mode.startswith(("Normal", "Hard")):
            continue  # Transcendence stages: which zone is which is not known
        rows = [[i["itemId"], i["name"], i["grade"], i["category"], round(i["chancePerClear"], 8)]
                for i in items if i["grade"] in GRADES and i["chancePerClear"] < 1]
        if rows:
            kept[mode.split(" ")[0]] = sorted(rows, key=lambda r: -r[4])
    if not kept:
        continue
    out["dungeons"][name] = kept
    ids = sorted(int(z) for z, n in zones.items() if n == name and 600000 <= int(z) <= 699999)
    for z in ids:
        mode = "Normal" if z % 10 == 1 else "Hard"
        if mode not in kept:
            if len(ids) > 1:
                continue  # that mode's drops are all better elsewhere: no table
            mode = next(iter(kept))
        out["zones"][str(z)] = [name, mode]

print("// Generated by dev/make_dungeon_rates.py: the game's dungeon drop rates, AION 2 Global (the game's")
print("// own reward tables, game version %s): per dungeon and mode the chance a reward box drops each item" % out["gameVersion"])
print("// at least once ([id, name, grade, category, chance]), and which zone is which mode (assumed from the")
print("// game's numbering). Do not edit by hand. AION 2 names and game data belong to NCSOFT.")
print("globalThis.INVENTORY_DUNGEON_RATES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";")
