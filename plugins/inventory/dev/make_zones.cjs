// Writes zones.js: the game's zone names by zone id, taken from the Map
// plugin's data.js (its zoneNames, read from the game's client), for the
// farm days' "where it came from".
//   node dev/make_zones.cjs   (from plugins/inventory)
const fs = require("node:fs");
const path = require("node:path");
const here = path.join(__dirname, "..");
require(path.join(here, "..", "map", "data.js"));
const names = globalThis.MAP_DATA?.zoneNames || Object.values(globalThis).find((v) => v && v.zoneNames)?.zoneNames;
if (!names) throw new Error("no zoneNames in ../map/data.js");
const out = {};
for (const id of Object.keys(names).sort((a, b) => a - b)) if (typeof names[id] === "string") out[id] = names[id];
fs.writeFileSync(path.join(here, "zones.js"),
  "// Generated by dev/make_zones.cjs from the Map plugin's data.js (zone names read from the game's\n" +
  "// client). Do not edit by hand. AION 2 names belong to NCSOFT.\n" +
  `globalThis.INVENTORY_ZONES = ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} zones`);
