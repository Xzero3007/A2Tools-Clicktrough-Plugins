"""Builds the Map plugin's areas.js: where the game itself puts each pet
monster, for the monsters whose spawn points the map knows only in part or
not at all.

    python3 -I dev/make_areas.py [<plugin folder>]

It reads Pet Finder's copy of the Pet Soul Tracker's sources.js (A2 Tools,
GPL-3.0: built by A2 Tools' tools/game-souls/gamesouls.py from the game's
own tables and map data) and the map's data.js (which map each of the game's
map ids is). For each monster that drops pet souls, per map:

    [spawns, x, y, zones]

spawns: how many spawn points the game has for it there; x, y: the middle one
of them (the spawn point with the smallest summed distance to the others, the
"at" of its Kibelisk in sources.js), in the map's world units (cm), a real
spawn point; zones: the English names of the subzones they lie in (the map
outlines those its regions know).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = sys.argv[1] if len(sys.argv) > 1 else HERE


def const(text, name):
    """The JSON value of `const <name> = ...;` in a script."""
    start = text.index(f"const {name} = ") + len(f"const {name} = ")
    value, _ = json.JSONDecoder().raw_decode(text[start:])
    return value


sources_js = open(os.path.join(OUT, "..", "pet-finder", "sources.js"), encoding="utf8").read()
sources = const(sources_js, "PET_SOURCES")
texts = const(sources_js, "SOURCE_TEXT")
data_js = open(os.path.join(OUT, "data.js"), encoding="utf8").read()
data, _ = json.JSONDecoder().raw_decode(data_js[data_js.index("globalThis.MAP_DATA = ") + len("globalThis.MAP_DATA = "):])


def en(key):
    t = texts.get(key)
    if isinstance(t, dict):
        return t.get("en") or next(iter(t.values()), key)
    return t or key


areas = {}
skipped = set()
for pet, s in sources.items():
    for d in s.get("drops", []):
        npc, mid, kib = d.get("npcId"), d.get("mapId"), d.get("kibelisk")
        if not npc or not d.get("spawns") or not kib or not kib.get("at"):
            continue
        key = data["zones"].get(str(mid))
        if not key or key not in data["maps"]:
            skipped.add(en(d.get("map", "")) or str(mid))
            continue
        x, y = kib["at"]
        zones = [en(z) for z in d.get("zones", [])]
        areas.setdefault(str(npc), {})[key] = [d["spawns"], round(x), round(y), zones]

with open(os.path.join(OUT, "areas.js"), "w", encoding="utf8") as f:
    f.write("// Generated by dev/make_areas.py from Pet Finder's copy of the Pet Soul Tracker's\n")
    f.write("// sources.js (A2 Tools, GPL-3.0, https://github.com/taengu/A2Tools-Plugins: the game's own\n")
    f.write("// tables and map data). Per monster and map: [spawns, x, y, zones], the number of the\n")
    f.write("// game's spawn points, the middle one of them (cm) and the subzones they lie in.\n")
    f.write("// Do not edit by hand. AION 2 names and game data belong to their respective owners.\n")
    f.write("globalThis.MAP_AREAS = ")
    json.dump(areas, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")

print(f"{len(areas)} monsters, {sum(len(v) for v in areas.values())} areas; maps the plugin has no picture of: "
      f"{', '.join(sorted(skipped)) or 'none'}")
