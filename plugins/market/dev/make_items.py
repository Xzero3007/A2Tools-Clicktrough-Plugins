"""Builds the Market plugin's items.js: every item's name, grade and icon,
for the listing of everything on the market.

    python3 -I dev/make_items.py ../inventory/data.js .

Taken from the Inventory plugin's data.js (made by its dev/make_data.py from
SkeeveAN's Aion-DPS-Meter, MIT, the game client's names, and Aion2Data's
icon names), without the currencies (never on the market) and the tickets.
"""
import json
import os
import sys


def main(src, out):
    text = open(src, encoding="utf8").read()
    data = json.loads(text[text.index("{"):].rstrip().rstrip(";"))
    items = {k: v for k, v in data["items"].items() if not k.startswith("93")}
    with open(os.path.join(out, "items.js"), "w", encoding="utf8") as f:
        f.write("// Generated by dev/make_items.py from the Inventory plugin's data.js (SkeeveAN's Aion-DPS-Meter, MIT,\n")
        f.write("// read from the game's client; icon names also Aion2Data): id -> [name, grade, icon without \"Icon_\"].\n")
        f.write("// Do not edit by hand. AION 2 names and game data belong to NCSOFT.\n")
        f.write(f"globalThis.MARKET_ITEMS = {{\"source\":{json.dumps(data['source']['items'])},\"items\":")
        json.dump(items, f, ensure_ascii=False, separators=(",", ":"))
        f.write("};\n")
    print(f"{len(items)} items")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
