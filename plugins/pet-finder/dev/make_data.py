# Builds data.js and images.js for the Pet Finder plugin from a PetTracker
# checkout (https://github.com/0Fox2Give/PetTracker, GPLv3).
#
#   python3 -I dev/make_data.py <PetTracker checkout> <plugin folder>
#
# data.js:   globalThis.PET_DATA  = { pets, npcs, regions, source }
# images.js: globalThis.PET_IMAGES = { portraits: {id: dataURL}, crystals: {family: dataURL} }
#
# Images are inlined as data: URLs because A2Tools inlines a plugin page on
# Linux, and WebKitGTK refuses files a sandboxed frame asks for by URL.
import base64, io, json, pathlib, subprocess, sys
from collections import defaultdict
from PIL import Image

src, out = map(pathlib.Path, sys.argv[1:3])
core = src / "src" / "Core"

catalog = json.loads((src / "assets" / "catalog.json").read_text())
sources = json.loads((core / "PetSources.json").read_text())
farming = json.loads((core / "FarmingLinks.json").read_text())
acquisitions = json.loads((core / "PetAcquisitions.json").read_text())
market_items = json.loads((core / "MarketItems.json").read_text())

FAMILY = {"Intellect": "Cogni", "Feral": "Fera", "Nature": "Natura", "Trans": "Varian", "Special": "Special"}
# PetTracker's map regions released on Global (PetFinder.cs, FarmingMap.Global).
GLOBAL_REGIONS = {"Verteron", "Altgard", "Chaotic Lower Reshanta"}

by_id = {p["Id"]: p for p in catalog}

# NPC -> pet, as CreaturePetMappings.cs: an NPC counts only when every source
# row for it names the same pet and that pet's catalog name matches.
npc_rows = defaultdict(list)
for row in sources["Rows"]:
    npc_rows[row["NpcId"]].append(row)
npcs = {}
npc_names = {}
for npc, rows in npc_rows.items():
    npc_names[npc] = rows[0].get("NpcName") or f"NPC #{npc}"
    claims = {(r["PetId"], r["CatalogName"]) for r in rows}
    if len(claims) == 1:
        pet_id, catalog_name = next(iter(claims))
        if pet_id in by_id and by_id[pet_id]["CatalogName"] == catalog_name:
            npcs[npc] = pet_id
# Gameplay-corroborated extras (CreaturePetMappings.cs).
for npc, pet_id, catalog_name in [(2100034, 1008, "OdSpider_01"), (2100231, 1168, "WaterEle_01"), (2400240, 1163, "Basilisk_01")]:
    if pet_id in by_id and by_id[pet_id]["CatalogName"] == catalog_name:
        npcs[npc] = pet_id

creatures = defaultdict(set)
for npc, pet_id in npcs.items():
    creatures[pet_id].add(npc_names[npc])

links = {r["PetId"]: r for r in farming["Rows"]}
acq = {a["PetId"]: a for a in acquisitions}

pets = []
for p in sorted(catalog, key=lambda p: p["Name"].lower()):
    if p["Name"].startswith("Pet #") or p["CatalogName"] == "TestDummy":
        continue
    link = links.get(p["Id"]) or {}
    maps = [m for m in link.get("Maps") or [] if m["Region"] in GLOBAL_REGIONS]
    # PetFinder.cs: audited SoulSources win over every NPC the decoder knows.
    if link.get("SoulSources") is not None:
        mobs = sorted({s["Name"] for s in link["SoulSources"]})
        mob_regions = sorted({s["Region"] for s in link["SoulSources"]})
    else:
        mobs = sorted(creatures.get(p["Id"], ()))
        mob_regions = []
    a = acq.get(p["Id"])
    # BlackMarket.WatchPet: audited to have no mob source, sold by the Black
    # Cloud Merchants, and an unlock item for it is known.
    watch = (link.get("SoulSources") == [] and bool(a) and "Black Cloud Merchants" in (a.get("Aliases") or [])
             and any(i["PetId"] == p["Id"] for i in market_items))
    entry = {
        "id": p["Id"],
        "name": p["Name"],
        "family": FAMILY.get(p["Category"], ""),
        "mobs": mobs,
        "regions": mob_regions,
        "maps": [{"region": m["Region"], "url": m["Url"]} for m in maps],
    }
    if watch:
        entry["watch"] = True
    if a:
        entry["acq"] = {"kind": a["Kind"], "how": a["Instructions"], "window": a.get("Window") or "",
                        "url": a.get("SourceUrl") or "", "aliases": a.get("Aliases") or [], "end": a.get("AnnouncedEnd") or ""}
    pets.append(entry)

commit = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
data = {
    "source": {"repo": "https://github.com/0Fox2Give/PetTracker", "commit": commit,
               "gameData": sources.get("SourceVersion", ""), "maps": farming.get("Provider", ""),
               "mapsVerified": farming.get("VerifiedUtc", "")},
    "pets": pets,
    "npcs": {str(k): v for k, v in sorted(npcs.items())},
    "npcNames": {str(k): npc_names[k] for k in sorted(npcs)},
    # Every pet id the game may send, for validating collection frames.
    "catalog": sorted(by_id),
    # Black Cloud Merchant unlock items: item id -> pet id (MarketItems.json).
    "market": {str(i["ItemId"]): i["PetId"] for i in market_items},
}
(out / "data.js").write_text(
    "// Generated by dev/make_data.py from PetTracker (GPLv3). Do not edit by hand.\n"
    "globalThis.PET_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")

def data_url(path, size):
    im = Image.open(path).convert("RGBA")
    im.thumbnail((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=80, method=6)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()

portraits = {}
for p in pets:
    f = src / "assets" / "portraits" / f"{p['id']}.png"
    if f.exists():
        portraits[str(p["id"])] = data_url(f, 72)
crystals = {}
for fam, name in [("Cogni", "cogni"), ("Fera", "fera"), ("Natura", "natura"), ("Varian", "varian"), ("Special", "special")]:
    f = src / "assets" / "crystals" / f"{name}.png"
    if f.exists():
        crystals[fam] = data_url(f, 32)
(out / "images.js").write_text(
    "// Generated by dev/make_data.py. Pet portraits and family crystals from PetTracker's assets\n"
    "// (game artwork; rights belong to their owners). Do not edit by hand.\n"
    "globalThis.PET_IMAGES = " + json.dumps({"portraits": portraits, "crystals": crystals}, separators=(",", ":")) + ";\n")

print(f"{len(pets)} pets, {len(npcs)} npc links, {len(portraits)} portraits, "
      f"data.js {(out / 'data.js').stat().st_size // 1024} KiB, images.js {(out / 'images.js').stat().st_size // 1024} KiB")
